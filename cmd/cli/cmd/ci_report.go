package cmd

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"sync"

	"github.com/nullify-platform/cli/internal/output"
)

// scannerReport holds every finding the report read for one scanner.
type scannerReport struct {
	ep       scannerEndpoint
	findings []json.RawMessage
	err      error
}

// reportRow is one line of the markdown table.
type reportRow struct {
	scanner  string
	severity severityLevel
	count    int
}

// collectScannerReports reads each scanner's list once, with no severity
// filter, so that every finding is read exactly once. It keeps only the
// findings the report counts.
func collectScannerReports(
	ctx context.Context,
	get findingsGetter,
	base map[string]string,
	endpoints []scannerEndpoint,
	scope repositoryScope,
) []scannerReport {
	reports := make([]scannerReport, len(endpoints))
	var wg sync.WaitGroup
	for i, ep := range endpoints {
		wg.Go(func() {
			findings, err := collectFindings(ctx, get, ep.path, base, scannerQueryParams(ep, "", scope))
			reports[i] = scannerReport{ep: ep, findings: countedFindings(ep, scope, findings), err: err}
		})
	}
	wg.Wait()
	return reports
}

// checkReportReads warns about each scanner the report could not read, and
// fails when it could read none of them. When every scanner refused access
// the failure is an authentication error.
func checkReportReads(reports []scannerReport) error {
	failed, denied := 0, 0
	for _, report := range reports {
		if report.err != nil {
			failed++
			fmt.Fprintf(os.Stderr, "Warning: failed to read %s: %v\n", report.ep.name, report.err)
		}
		if isAccessDenied(report.err) {
			denied++
		}
	}
	if denied == len(reports) {
		return authError("every scanner refused access (401 or 403), cannot generate report")
	}
	if failed == len(reports) {
		return networkError("all API requests failed, cannot generate report")
	}
	if failed > 0 {
		fmt.Fprintf(os.Stderr, "Warning: %d API requests failed while generating the report\n", failed)
	}
	return nil
}

// reportRows counts each scanner's findings by their own severity, most
// severe first, leaving out severities with no findings.
func reportRows(reports []scannerReport) []reportRow {
	rows := []reportRow{}
	for _, report := range reports {
		counts := map[severityLevel]int{}
		for _, finding := range report.findings {
			counts[findingSeverity(report.ep, finding)]++
		}
		for _, severity := range reportSeverities {
			if counts[severity] > 0 {
				rows = append(rows, reportRow{scanner: report.ep.name, severity: severity, count: counts[severity]})
			}
		}
	}
	return rows
}

func printMarkdownReport(rows []reportRow) {
	fmt.Println("## Nullify Security Report")
	fmt.Println()
	fmt.Println("| Scanner | Severity | Count |")
	fmt.Println("|---------|----------|-------|")
	for _, row := range rows {
		fmt.Printf("| %s | %s | %d |\n", row.scanner, row.severity, row.count)
	}
	fmt.Println()
	fmt.Println("*Generated by [Nullify CLI](https://github.com/nullify-platform/cli)*")
}

func printSARIFReport(reports []scannerReport) error {
	all := make([]json.RawMessage, 0)
	for _, report := range reports {
		all = append(all, report.findings...)
	}
	wrapped, err := json.Marshal(map[string]any{"findings": all, "total": len(all)})
	if err != nil {
		return networkError("failed to build SARIF report: %w", err)
	}
	sarifBytes, err := output.SARIFBytes(wrapped)
	if err != nil {
		return networkError("failed to build SARIF report: %w", err)
	}
	fmt.Println(string(sarifBytes))
	return nil
}
