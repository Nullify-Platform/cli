// Generator safety: stale output removal, unmapped path rejection and the
// committed route to command name lock.
package main

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const generatedFileMarker = "// Code generated by scripts/generate/main.go. DO NOT EDIT."

// ErrUnmappedPath is returned when the spec has a path whose prefix is in
// neither serviceMapping nor excludePrefixes.
var ErrUnmappedPath = errors.New("path prefix is in neither serviceMapping nor excludePrefixes")

// removeGeneratedFiles deletes every Go file in dirs that the generator wrote,
// so that a service or model file the spec no longer produces cannot survive a
// regeneration. Hand-written files in the same directories are left alone.
func removeGeneratedFiles(dirs ...string) error {
	for _, dir := range dirs {
		files, err := filepath.Glob(filepath.Join(dir, "*.go"))
		if err != nil {
			return err
		}
		for _, file := range files {
			content, err := os.ReadFile(file)
			if err != nil {
				return err
			}
			if !strings.HasPrefix(string(content), generatedFileMarker) {
				continue
			}
			if err := os.Remove(file); err != nil {
				return err
			}
		}
	}
	return nil
}

var pathParamPattern = regexp.MustCompile(`\{[^}]+\}`)

// routeKey identifies an operation independently of its path parameter names,
// so that renaming {id} to {findingId} does not rename the command.
func routeKey(method, path string) string {
	return strings.ToUpper(method) + " " + pathParamPattern.ReplaceAllString(path, "{}")
}

// commandNames is the committed record of the command name given to each route.
// A row stays after its route leaves the spec, so a later route cannot reuse the
// name with a different meaning.
type commandNames struct {
	useByRoute map[string]string
	service    map[string]string
}

func newCommandNames() *commandNames {
	return &commandNames{useByRoute: map[string]string{}, service: map[string]string{}}
}

// loadCommandNames reads the lock file. A missing file gives an empty lock.
func loadCommandNames(path string) (*commandNames, error) {
	names := newCommandNames()
	content, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return names, nil
	}
	if err != nil {
		return nil, err
	}
	for i, line := range strings.Split(strings.TrimSpace(string(content)), "\n") {
		if line == "" {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 3 {
			return nil, fmt.Errorf("%s:%d: want route, service and command name", path, i+1)
		}
		names.useByRoute[fields[0]] = fields[2]
		names.service[fields[0]] = fields[1]
	}
	return names, nil
}

func (n *commandNames) write(path string) error {
	routes := make([]string, 0, len(n.useByRoute))
	for route := range n.useByRoute {
		routes = append(routes, route)
	}
	sort.Strings(routes)

	var sb strings.Builder
	for _, route := range routes {
		fmt.Fprintf(&sb, "%s\t%s\t%s\n", route, n.service[route], n.useByRoute[route])
	}
	return os.WriteFile(path, []byte(sb.String()), 0644)
}

func (n *commandNames) takenIn(service string) map[string]bool {
	taken := map[string]bool{}
	for route, use := range n.useByRoute {
		if n.service[route] == service {
			taken[use] = true
		}
	}
	return taken
}
